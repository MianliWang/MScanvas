# Extracts a historical frontend for the PM9.1 journey baseline. Test-only.
#
# `git archive` of one commit's `apps/desktop` (without `src-tauri`) under
# .tmp/pm91-j16/<short id>/, the checkout's `apps/desktop/node_modules` joined
# into it (valid only while the lockfile and manifests are unchanged since that
# commit; this script refuses otherwise), and a wrapper Vite config that gives
# it a cache of its own. The checkout, its branch and its worktrees are not
# touched. Prints the identities and the two variables wdio.baseline.conf.ts
# reads.
#
#   pwsh -File e2e/baseline/prepare-baseline-app.ps1 [-Commit d56b17b]
param([string] $Commit = "d56b17b", [string] $Root = ".tmp/pm91-j16")
$ErrorActionPreference = "Stop"

$repo = (git rev-parse --show-toplevel).Trim()
Set-Location $repo
$full = (git rev-parse "$Commit^{commit}").Trim()
$tree = (git rev-parse "$Commit^{tree}").Trim()

# The joined node_modules is the checkout's: refuse a commit whose dependency
# graph differs from it.
$deps = @("pnpm-lock.yaml", "pnpm-workspace.yaml", "apps/desktop/package.json")
$changed = (git diff --name-only $full HEAD -- @deps) -join ", "
if ($changed) { throw "dependency files differ from $full ($changed); the joined node_modules would not be that commit's" }

$dest = Join-Path $repo (Join-Path $Root $full.Substring(0, 7))
$app = Join-Path $dest "apps/desktop"
$tar = "$dest-apps-desktop.tar"
New-Item -ItemType Directory -Force $dest | Out-Null
$paths = @(
  "apps/desktop/index.html", "apps/desktop/package.json", "apps/desktop/tsconfig.app.json",
  "apps/desktop/tsconfig.json", "apps/desktop/tsconfig.node.json", "apps/desktop/vite.config.ts",
  "apps/desktop/src"
)
git archive --format=tar -o $tar $full @paths
tar -xf $tar -C $dest

$link = Join-Path $app "node_modules"
if (-not (Test-Path $link)) {
  New-Item -ItemType Junction -Path $link -Target (Join-Path $repo "apps/desktop/node_modules") | Out-Null
}

# Beside the historical config, so its bare imports resolve through the joined
# node_modules; the config itself is used unchanged.
$wrapper = Join-Path $app "vite.baseline.config.ts"
@'
// Generated by e2e/baseline/prepare-baseline-app.ps1: the commit's own Vite
// config, unchanged, with a cache of its own so the checkout's is not shared.
import { fileURLToPath } from "node:url";

import base from "./vite.config";

export default { ...base, cacheDir: fileURLToPath(new URL("../../vite-cache", import.meta.url)) };
'@ | Set-Content -Encoding utf8NoBOM -NoNewline $wrapper

$hash = (Get-FileHash -Algorithm SHA256 $tar).Hash.ToLower()
"commit $full"
"tree $tree"
"archive $tar sha256 $hash"
"MSCANVAS_BASELINE_APP_DIR=$app"
"MSCANVAS_BASELINE_VITE_CONFIG=$wrapper"
